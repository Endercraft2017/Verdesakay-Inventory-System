import { beforeAll, afterAll, afterEach, it, expect, vi } from 'vitest';
import { generateSync } from 'otplib';
import { setupApp, cleanup, login, createEmployee, type TestContext } from './helpers';
let ctx: TestContext; let admin: string;
beforeAll(async () => { ctx = await setupApp(); admin = await login(ctx.api); });
afterEach(() => vi.restoreAllMocks());
afterAll(() => cleanup(ctx));
const header = (t: string) => ({ Authorization: `Bearer ${t}` });
it('enrolls with password plus proof, encrypts the secret, revokes sessions and rejects replay', async () => {
  const account = await createEmployee(ctx.api, admin, { username: 'mfa-user' });
  const setup = await ctx.api.post('/api/auth/mfa/setup').set(header(account.token)).send({ current_password: account.password });
  expect(setup.status).toBe(200); expect(setup.body.uri).toMatch(/^otpauth:\/\/totp\//);
  const secret = setup.body.secret;
  const code = generateSync({ secret });
  expect((await ctx.api.post('/api/auth/mfa/enable').set(header(account.token)).send({ current_password: account.password, code: 'invalid' })).status).toBe(400);
  const enabled = await ctx.api.post('/api/auth/mfa/enable').set(header(account.token)).send({ current_password: account.password, code });
  expect(enabled.status).toBe(200); expect(enabled.body.recovery_codes).toHaveLength(8);
  expect((await ctx.api.get('/api/auth/me').set(header(account.token))).status).toBe(401);
  const creds = { username: account.username, password: account.password };
  expect((await ctx.api.post('/api/auth/login').send(creds)).body.mfa_required).toBe(true);
  expect((await ctx.api.post('/api/auth/login').send({ ...creds, mfa_code: code })).status).toBe(401);
  const { queryOne } = await import('../src/shared/db');
  const stored = queryOne<{ secret: string; recovery_hashes: string }>('SELECT * FROM user_mfa WHERE user_id = ?', account.id)!;
  expect(stored.secret).not.toBe(secret); expect(stored.recovery_hashes).not.toContain(enabled.body.recovery_codes[0]);
  const recovered = await ctx.api.post('/api/auth/login').send({ ...creds, mfa_code: enabled.body.recovery_codes[0] });
  expect(recovered.status).toBe(200);
  expect((await ctx.api.post('/api/auth/login').send({ ...creds, mfa_code: enabled.body.recovery_codes[0] })).status).toBe(401);
  const time = Date.now() + 60_000; vi.spyOn(Date, 'now').mockReturnValue(time);
  const nextCode = generateSync({ secret, epoch: time / 1000 });
  expect((await ctx.api.post('/api/auth/login').send({ ...creds, mfa_code: nextCode })).status).toBe(200);
  expect((await ctx.api.post('/api/auth/login').send({ ...creds, mfa_code: nextCode })).status).toBe(401);
  const status = await ctx.api.get('/api/auth/mfa').set(header(recovered.body.token));
  expect(status.body).toEqual({ enabled: true, recovery_codes_remaining: 7 });
  expect(JSON.stringify(status.body)).not.toContain(secret);
});
it('binds enrollment to a verified session, expires setup and requires a second factor to disable', async () => {
  const account = await createEmployee(ctx.api, admin, { username: 'mfa-session' });
  expect((await ctx.api.post('/api/auth/mfa/setup').set(header(account.token)).send({ current_password: 'wrong' })).status).toBe(403);
  const setup = await ctx.api.post('/api/auth/mfa/setup').set(header(account.token)).send({ current_password: account.password });
  const second = await login(ctx.api, account.username, account.password);
  const code = generateSync({ secret: setup.body.secret });
  expect((await ctx.api.post('/api/auth/mfa/enable').set(header(second)).send({ current_password: account.password, code })).status).toBe(400);
  const enabled = await ctx.api.post('/api/auth/mfa/enable').set(header(account.token)).send({ current_password: account.password, code });
  const signed = await ctx.api.post('/api/auth/login').send({ username: account.username, password: account.password, mfa_code: enabled.body.recovery_codes[0] });
  expect((await ctx.api.post('/api/auth/mfa/disable').set(header(signed.body.token)).send({ current_password: account.password })).status).toBe(403);
  expect((await ctx.api.post('/api/auth/mfa/setup').set(header(signed.body.token)).send({ current_password: account.password })).status).toBe(409);
  expect((await ctx.api.post('/api/auth/mfa/disable').set(header(signed.body.token)).send({ current_password: account.password, code: enabled.body.recovery_codes[1] })).status).toBe(200);
  expect((await ctx.api.get('/api/auth/me').set(header(signed.body.token))).status).toBe(401);
  expect(await login(ctx.api, account.username, account.password)).toBeTruthy();
  const session = await login(ctx.api, account.username, account.password);
  await ctx.api.post('/api/auth/mfa/setup').set(header(session)).send({ current_password: account.password });
  vi.spyOn(Date, 'now').mockReturnValue(Date.now() + 601_000);
  expect((await ctx.api.post('/api/auth/mfa/enable').set(header(session)).send({ current_password: account.password, code })).status).toBe(400);
});
