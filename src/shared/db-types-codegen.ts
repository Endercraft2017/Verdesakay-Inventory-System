/**
 * Generates src/shared/db-types.ts (the Kysely `DB` interface) from a live SQLite schema,
 * so query-builder column types always match what createSchema()/migrate() actually built.
 *
 *   npm run db:types     regenerate after changing the schema
 *
 * tests/db-types.test.ts fails when the checked-in file is stale, so a schema change can't
 * silently leave the types behind.
 */
import type { DatabaseSync } from 'node:sqlite';

interface ColumnInfo { name: string; type: string; notnull: number; dflt_value: string | null; pk: number }

/** SQLite declared type → TS type, per SQLite's type-affinity rules. */
function tsType(declared: string): string {
  const t = declared.toUpperCase();
  if (t.includes('INT')) return 'number';
  if (t.includes('CHAR') || t.includes('CLOB') || t.includes('TEXT')) return 'string';
  if (t.includes('BLOB')) return 'Uint8Array';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB') || t.includes('NUM') || t.includes('DEC')) return 'number';
  return t === '' ? 'string' : 'unknown'; // untyped columns (FTS5) hold text
}

function pascal(name: string): string {
  return name.split('_').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

export function renderDbTypes(conn: DatabaseSync): string {
  const tables = (conn.prepare(
    `SELECT name FROM sqlite_master
     WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
       AND name NOT IN (SELECT name || '_' || s FROM sqlite_master, (SELECT 'data' s UNION SELECT 'idx' UNION SELECT 'content' UNION SELECT 'docsize' UNION SELECT 'config'))
     ORDER BY name`
  ).all() as unknown as Array<{ name: string }>).map((r) => r.name);

  const out: string[] = [
    '/* eslint-disable */',
    '// GENERATED by `npm run db:types` from the live schema (src/shared/db-types-codegen.ts).',
    '// Do not edit by hand. tests/db-types.test.ts fails when this is stale.',
    "import type { Generated } from 'kysely';",
    '',
  ];
  for (const table of tables) {
    const cols = conn.prepare(`PRAGMA table_info("${table}")`).all() as unknown as ColumnInfo[];
    out.push(`export interface ${pascal(table)} {`);
    for (const c of cols) {
      let ty = tsType(c.type);
      const nullable = c.notnull === 0 && c.pk === 0;
      if (nullable) ty += ' | null';
      // Optional on insert: has a DEFAULT, or is the INTEGER PRIMARY KEY (rowid alias).
      const generated = c.dflt_value !== null || (c.pk === 1 && c.type.toUpperCase() === 'INTEGER');
      out.push(`  ${c.name}: ${generated ? `Generated<${ty}>` : ty};`);
    }
    out.push('}', '');
  }
  out.push('export interface DB {');
  for (const table of tables) out.push(`  ${table}: ${pascal(table)};`);
  out.push('}', '');
  return out.join('\n');
}
