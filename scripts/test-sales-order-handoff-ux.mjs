import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';

const output = path.resolve('work/sales-order-handoff');
fs.mkdirSync(output, { recursive: true });
const server = spawn(process.execPath, ['--import', 'tsx', 'scripts/browser/editor-ux-server.ts'], { stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
try {
  const port = await new Promise((resolve, reject) => {
    server.stdout.on('data', data => { const m = String(data).match(/EDITOR_UX_PORT=(\d+)/); if (m) resolve(m[1]); });
    server.on('exit', code => reject(new Error('server exited ' + code)));
  });
  const base = `http://127.0.0.1:${port}`;
  const api = async (method, route, token, body, status = 200) => {
    const r = await fetch(base + '/api' + route, { method, headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: body == null ? undefined : JSON.stringify(body) });
    const data = await r.json(); assert.equal(r.status, status, route + ': ' + JSON.stringify(data)); return data;
  };
  const admin = (await api('POST', '/auth/login', '', { username: 'admin', password: 'admin123' })).token;
  const customer = await api('POST', '/customers', admin, { name: 'Searchable Buyer', phone: '09123456789' }, 201);
  const noBom = await api('POST', '/inventory', admin, { name: 'No recipe product' }, 201);
  await api('PUT', '/finished-products/' + noBom.id, admin, { components: [] });
  const unplannable = await api('POST', '/orders', admin, { type: 'sale', customer_name: 'No recipe customer', items: [{ item_id: noBom.id, name: 'No recipe product', quantity: 1 }] }, 201);
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  for (const width of [1440, 390]) {
    const raw = await api('POST', '/inventory', admin, { name: `Handoff raw ${width}`, quantity: 10 }, 201);
    const product = await api('POST', '/inventory', admin, { name: `Handoff finished ${width}`, quantity: 1 }, 201);
    await api('PUT', '/finished-products/' + product.id, admin, { components: [{ component_item_id: raw.id, quantity: 1 }] });
    const shortage = await api('POST', '/orders', admin, { type: 'sale', customer_name: `Production customer ${width}`, items: [{ item_id: product.id, name: `Handoff finished ${width}`, quantity: 2, unit_price: 100 }] }, 201);
    const context = await browser.newContext({ viewport: { width, height: 900 }, serviceWorkers: 'block' });
    await context.addInitScript(token => localStorage.setItem('vds_token', token), admin);
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/app'); await page.waitForFunction(() => typeof App !== 'undefined' && App.getMe());
    await page.evaluate(() => App.navigate('orders', { type: 'job' }));
    await page.getByText('Customer Job Orders · View only').waitFor();
    assert.equal(await page.locator('#ord-new, #ord-empty-new, [data-produce]').count(), 0);
    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator('#ord-new').click();
    const search = page.locator('#ord-customer-search');
    await search.fill('Searchable'); await search.press('ArrowDown'); await search.press('Enter');
    assert.equal(await page.locator('[data-f="customer_id"]').inputValue(), String(customer.id));
    await page.locator('[data-f="expected_date"]').fill('2026-12-15');
    assert.equal(await page.locator('[data-f="status"]').count(), 0);
    const a11y = await new AxeBuilder({ page }).include('.order-editor').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
    assert.deepEqual(a11y.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), []);
    assert(await page.locator('.order-editor .modal').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await page.screenshot({ path: path.join(output, `${width}-capture.png`) });
    await search.fill('Walk-in Buyer');
    assert.equal(await page.locator('[data-f="customer_id"]').inputValue(), '');
    await page.locator('#ord-walk-in').click();
    assert.match(await page.locator('.order-customer-choice').innerText(), /Walk-in/);
    await page.locator('#ord-add-blank').click();
    await page.locator('[data-row="0"] [data-k="name"]').fill('Service fee');
    await page.locator('.order-editor [data-confirm]').click();
    await page.locator('.order-editor').waitFor({ state: 'detached' });
    const list = await api('GET', '/orders?type=sale&q=Walk-in%20Buyer', admin);
    assert.equal(list[0].customer_id, null);
    assert.equal((await api('GET', '/orders/' + list[0].id, admin)).expected_date, '2026-12-15');
    const own = await api('POST', '/deliveries', admin, { order_id: list[0].id, delivery_mode: 'own' }, 201);
    await api('POST', `/deliveries/${own.id}/complete`, admin, { outcome: 'delivered' });
    const courier = await api('POST', '/deliveries', admin, { order_id: list[0].id, delivery_mode: 'courier', courier_name: 'Test carrier' }, 201);
    await api('POST', `/deliveries/${courier.id}/complete`, admin, { outcome: 'courier_handoff' });
    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`tr[data-open="${list[0].id}"]`).click();
    await page.getByText('Customer delivery:', { exact: false }).waitFor();
    await page.getByText('Courier pickup / handoff:', { exact: false }).waitFor();
    const dates = (await api('GET', '/orders/' + list[0].id, admin)).delivery_events.map(e => e.delivered_at);
    for (const date of dates) assert((await page.locator('.order-editor').innerText()).includes(await page.evaluate(value => UI.fmtDate(value), date)));
    await page.locator('.order-editor [data-close]').first().click();

    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`[data-stock="${shortage.id}"]`).click();
    await page.locator('[data-approve]').waitFor();
    assert.match(await page.locator('#stock-review').innerText(), /Short 1/);
    await page.screenshot({ path: path.join(output, `${width}-approval.png`) });
    await page.locator('[data-approve]').click();
    await page.locator('.order-review').waitFor({ state: 'detached' });
    const linked = (await api('GET', '/orders/' + shortage.id + '/availability', admin)).lines[0].linked_job_orders;
    assert.equal(linked.length, 1); assert.equal(linked[0].remaining, 1); assert.equal(linked[0].status, 'draft');
    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`[data-stock="${shortage.id}"]`).click();
    await page.locator(`[data-linked-jo="${linked[0].id}"]`).click();
    await page.getByText('Linked production · ' + linked[0].number).waitFor();
    assert.equal(await page.locator('.modal-overlay:last-child [data-confirm]').count(), 0);
    await page.locator('.modal-overlay:last-child [data-close]').first().click();
    await page.locator('.order-review [data-close]').first().click();
    const repeat = await api('POST', `/orders/${shortage.id}/status`, admin, { status: 'approved' });
    assert.deepEqual(repeat.production_drafts, []);
    const stocked = await api('POST', '/inventory', admin, { name: `RTS stocked ${width}`, quantity: 1 }, 201);
    const stockedOrder = await api('POST', '/orders', admin, { type: 'sale', items: [{ item_id: stocked.id, name: `RTS stocked ${width}`, quantity: 1 }] }, 201);
    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`[data-stock="${stockedOrder.id}"]`).click();
    await page.getByText('Stock covers this order').waitFor();
    await page.locator('[data-approve]').click();
    await page.locator('.order-review').waitFor({ state: 'detached' });
    assert.deepEqual((await api('POST', `/orders/${stockedOrder.id}/status`, admin, { status: 'approved' })).production_drafts, []);

    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`[data-stock="${unplannable.id}"]`).click();
    await page.locator('[data-approve]').waitFor();
    await page.locator('[data-approve]').click();
    await page.getByText('Production → Finished Products', { exact: false }).waitFor();
    assert.equal((await api('GET', '/orders/' + unplannable.id, admin)).status, 'open');
    await page.locator('.order-review [data-close]').first().click();
    const stalePart = await api('POST', '/inventory', admin, { name: `Stale part ${width}`, quantity: 1 }, 201);
    const stale = await api('POST', '/orders', admin, { type: 'sale', items: [{ item_id: stalePart.id, name: `Stale part ${width}`, quantity: 1 }] }, 201);
    await page.evaluate(() => App.navigate('orders', { type: 'sale' }));
    await page.locator(`[data-stock="${stale.id}"]`).click(); await page.locator('[data-approve]').waitFor();
    await api('POST', `/inventory/${stalePart.id}/adjust`, admin, { change: -1 });
    await page.locator('[data-approve]').click();
    await page.getByText('Review the refreshed stock before deciding', { exact: false }).waitFor();
    assert.equal((await api('GET', '/orders/' + stale.id, admin)).status, 'open');
    await page.locator('.order-review [data-close]').first().click();
    const staff = await api('POST', '/users', admin, { username: `csr_browser_${width}`, full_name: 'Browser CSR', password: 'test-password-123', role: 'csr' }, 201);
    assert(staff.id);
    const csr = (await api('POST', '/auth/login', '', { username: `csr_browser_${width}`, password: 'test-password-123' })).token;
    const csrContext = await browser.newContext({ viewport: { width, height: 900 }, serviceWorkers: 'block' });
    await csrContext.addInitScript(token => localStorage.setItem('vds_token', token), csr);
    const csrPage = await csrContext.newPage(); await csrPage.goto(base + '/app'); await csrPage.waitForFunction(() => typeof App !== 'undefined' && App.getMe());
    await csrPage.evaluate(() => App.navigate('orders', { type: 'job' }));
    assert.equal(await csrPage.locator('#ord-new').count(), 0);
    await csrContext.close();
    assert.deepEqual(errors, []);
    console.log(`${width}px: capture, stock approval, no-BOM, stale stock, delivery modes and CSR read-only JO passed`);
    await context.close();
  }
} finally { await browser?.close(); server.kill('SIGTERM'); }
