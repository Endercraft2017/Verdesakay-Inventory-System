  await api('POST','/orders/'+order.id+'/accept-release',admin,{});
  await api('POST','/orders/'+order.id+'/release',admin,{bulk:[{item_id:frame.id,quantity:1}]});
  browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
  await context.addInitScript(t=>localStorage.setItem('vds_token',t),admin);
  const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const open=async()=>{const url=base+'/m#/so?id='+order.id+'&step=trip';if(page.url()===url)await page.reload();else await page.goto(url);try{await page.locator('#trip-continue').waitFor({timeout:8000});}catch(e){console.log('Trip screen:',(await page.locator('#m-view').innerText()).slice(0,800));throw e;}};
  await open();
  await page.locator('#trip-continue').click();
  await page.getByText('Choose complete CKD kits',{exact:false}).waitFor();
  assert.equal((await api('GET','/release-slips/orders/'+order.id+'/context',admin)).slips.length,0);
  console.log('Phone PWA: lone frame blocked before release review');
  await api('POST','/orders/'+order.id+'/release',admin,{bulk:[{item_id:wheel.id,quantity:2}]});
  await open();
  await page.getByText('2 held here',{exact:false}).waitFor();
  await page.locator('#trip-continue').click();
  await page.getByRole('heading',{name:'Verify release package'}).waitFor();
  console.log('Phone PWA: whole kit advances to package review');
  await api('POST','/orders/'+order.id+'/release',admin,{bulk:[{item_id:frame.id,quantity:1}]});
  await open();
  await page.locator('[data-load-line]').filter({hasText:'Phone CKD edge frame'}).locator('[data-load-bulk]').fill('2');
  await page.locator('#trip-continue').click();
  await page.getByText('Choose complete CKD kits',{exact:false}).waitFor();
  await api('POST','/orders/'+order.id+'/release/unreserve',admin,{bulk:[{item_id:frame.id,quantity:1}]});
  console.log('Phone PWA: extra frame blocked until undo');
  await open();
  await page.locator('#trip-continue').click();
  await page.getByRole('heading',{name:'Verify release package'}).waitFor();
  await page.locator('#rel-go').click();
  await page.locator('[data-token]').fill(auth.token);
  await page.locator('[data-verify]').click();
  await page.getByText(' · Valid',{exact:false}).first().waitFor();
  await page.locator('#rel-go').click();
  const chooser=page.waitForEvent('filechooser');
  await page.locator('[data-cap]').click();
  await (await chooser).setFiles({name:'ckd-handoff.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6gAAAAABJRU5ErkJggg==','base64')});
  await page.locator('[data-thumbs] img').waitFor();
  const canvas=page.locator('[data-sign] canvas');
  await canvas.scrollIntoViewIfNeeded();
  const box=await canvas.boundingBox();assert(box);
  await page.mouse.move(box.x+20,box.y+20);await page.mouse.down();await page.mouse.move(box.x+90,box.y+45,{steps:10});await page.mouse.up();
  await page.locator('#rel-go').click();
  await page.locator('#rel-go').click();
  await page.locator('#rel-ok').check();
  await page.locator('#rel-post').click();
  await page.locator('#handoff-review').waitFor();
  assert.equal((await api('GET','/release-slips/orders/'+order.id+'/context',admin)).slips.length,1);
  assert.equal((await api('GET','/inventory/'+frame.id,admin)).quantity,1);
  assert.equal((await api('GET','/inventory/'+wheel.id,admin)).quantity,2);
  console.log('Phone PWA: complete CKD kit ships with handoff proof and one component stock-out');
