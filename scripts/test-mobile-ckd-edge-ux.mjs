  const product=await api('POST','/inventory',admin,{name:'Phone CKD edge product'},201);
  const frame=await api('POST','/inventory',admin,{name:'Phone CKD edge frame',quantity:2},201);
  const wheel=await api('POST','/inventory',admin,{name:'Phone CKD edge wheel',quantity:4},201);
  await api('PUT','/finished-products/'+product.id,admin,{components:[{component_item_id:frame.id,quantity:1},{component_item_id:wheel.id,quantity:2}]});
  const order=await api('POST','/orders',admin,{type:'sale',status:'approved',customer_name:'Phone kit edge',items:[{item_id:product.id,name:'Phone CKD edge product',quantity:2,unit_price:100,fulfillment_mode:'ckd'}]},201);
